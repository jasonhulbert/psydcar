"""Build the dashboard's Lucide icon sprite from a lucide-static package.

Usage: python scripts/build-dashboard-icons.py PATH_TO_LUCIDE_STATIC

PATH_TO_LUCIDE_STATIC is an unpacked lucide-static package, for example the
`package` folder of a tarball downloaded from the npm registry. Add an icon to
ICONS, rerun, and reference it in the dashboard as `#NAME`. The server inlines
the sprite into index.html.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path


ICONS = [
    "book-open",
    "bot",
    "check",
    "chevron-left",
    "chevron-right",
    "circle-alert",
    "circle-check",
    "circle-x",
    "copy",
    "folder-plus",
    "git-pull-request",
    "inbox",
    "info",
    "layers",
    "loader-circle",
    "pencil",
    "plug",
    "plus",
    "refresh-cw",
    "search",
    "trash-2",
    "triangle-alert",
    "x",
]

OUTPUT = Path(__file__).resolve().parent.parent / "src" / "psydcar" / "dashboard_assets" / "icons.svg"


def main(package: Path) -> None:
    version = json.loads((package / "package.json").read_text())["version"]
    symbols = []
    for name in ICONS:
        source = (package / "icons" / f"{name}.svg").read_text()
        body = re.search(r"<svg[^>]*>(.*)</svg>", source, re.S)
        if body is None:
            raise ValueError(f"Could not read {name}.svg")
        shapes = " ".join(line.strip() for line in body.group(1).strip().splitlines())
        symbols.append(f'  <symbol id="{name}" viewBox="0 0 24 24">{shapes}</symbol>')
    OUTPUT.write_text(
        f"<!-- Lucide icons v{version} (https://lucide.dev), ISC License, Copyright (c) Lucide Icons and Contributors. "
        "Generated by scripts/build-dashboard-icons.py. -->\n"
        '<svg xmlns="http://www.w3.org/2000/svg" class="icon-sprite" aria-hidden="true" focusable="false">\n'
        + "\n".join(symbols)
        + "\n</svg>\n"
    )
    print(f"Wrote {len(symbols)} icons to {OUTPUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(Path(sys.argv[1]))
